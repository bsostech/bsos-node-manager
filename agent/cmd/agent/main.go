// Node Agent entry point: reverse tunnel, host metrics and log buffering next to a Besu node.
// Subcommand: `agent join --platform <host:port> --token <join token>` (bootstrap).
// The agent knows nothing about Besu: it writes no Besu files, never restarts it, holds no RPC credentials;
// the platform reaches the node's local endpoints through the tunnel with X-Target.
package main

import (
	"context"
	_ "embed"
	"flag"
	"fmt"
	"log"
	"net/http"
	"os"
	"os/signal"
	"path/filepath"
	"syscall"
	"time"

	"github.com/joho/godotenv"

	"besu-manager/agent/internal/agentstatus"
	"besu-manager/agent/internal/certstore"
	"besu-manager/agent/internal/hostmetrics"
	"besu-manager/agent/internal/join"
	"besu-manager/agent/internal/logsink"
	"besu-manager/agent/internal/logspool"
	"besu-manager/agent/internal/version"
	"besu-manager/agent/internal/wsclient"
)

const sampleInterval = 5 * time.Second

func getenv(key, def string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return def
}

func runJoin(args []string) {
	fs := flag.NewFlagSet("join", flag.ExitOnError)
	platform := fs.String("platform", "localhost:8443", "platform mTLS address (host:port)")
	token := fs.String("token", "", "join token (required; the node id is bound to the token)")
	stateDir := fs.String("state-dir", getenv("AGENT_STATE_DIR", "state"), "directory for certificate material")
	reEnroll := fs.Bool("re-enroll", false, "re-enroll: the node is already in the platform inventory but its certificate is no longer valid; get a new certificate (keeps the node id and inventory history)")
	_ = fs.Parse(args)
	if *token == "" {
		fs.Usage()
		os.Exit(2)
	}
	if err := join.Run(context.Background(), join.Options{
		PlatformAddr: *platform, Token: *token, StateDir: *stateDir, ReEnroll: *reEnroll,
	}); err != nil {
		log.Fatalf("join: %v", err)
	}
}

// runOrg prints this agent's organization (the O in its certificate). upgrade-agent.sh uses it to build the
// platform's TLS server name, so node hosts do not need openssl.
func runOrg(args []string) {
	fs := flag.NewFlagSet("org", flag.ExitOnError)
	stateDir := fs.String("state-dir", getenv("AGENT_STATE_DIR", "state"), "directory for certificate material")
	_ = fs.Parse(args)
	cs, err := certstore.Load(*stateDir)
	if err != nil {
		log.Fatalf("org: %v", err)
	}
	if cs == nil {
		log.Fatalf("org: no certificate in %s", *stateDir)
	}
	fmt.Println(cs.Org())
}

// Third-party license notices (generated by tools/deps/notices.py): the agent binary is distributed to node
// hosts on its own, so the notices must ship with the binary
//
//go:embed NOTICES.txt
var notices string

func main() {
	_ = godotenv.Load()

	if len(os.Args) > 1 && os.Args[1] == "licenses" {
		fmt.Print(notices)
		return
	}

	if len(os.Args) > 1 && os.Args[1] == "org" {
		runOrg(os.Args[2:])
		return
	}

	if len(os.Args) > 1 && os.Args[1] == "join" {
		runJoin(os.Args[2:])
		return
	}

	// version subcommand: print the build version and exit (upgrade-agent.sh compares it with the platform's
	// version to decide whether to swap the binary).
	if len(os.Args) > 1 && os.Args[1] == "version" {
		fmt.Println(version.Version)
		return
	}

	// SIGTERM (docker stop, systemctl stop) and Ctrl-C: close the tunnel with a close frame so the platform sees
	// the node go offline at once, then exit 0. In a container the agent is PID 1, which ignores SIGTERM
	// unless it is handled, so without this every stop waited for the runtime's SIGKILL.
	ctx, cancel := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer cancel()

	// DISK_PATH: optional, the path used to measure disk usage. A docker sidecar that mounts the host rootfs
	// points it there; otherwise it measures the container's own root.
	host := hostmetrics.New(os.Getenv("DISK_PATH"))
	go host.Run(ctx, sampleInterval)

	// Log intake: listens on 127.0.0.1:5170 by default; Besu sends logs here using the log4j2 config from the
	// platform. If nobody sends, it stays empty.
	// LOG_SINK can rebind to a local bridge interface IP (for containers on a bridge network); an invalid
	// address is a config error and exits.
	// Failing to open (e.g. port in use) does not exit: logs are optional and must not take down the tunnel
	// or host metrics.
	sinkAddr := getenv("LOG_SINK", logsink.DefaultAddr)
	if err := logsink.ValidateAddr(sinkAddr); err != nil {
		log.Fatalf("LOG_SINK: %v", err)
	}
	// ALLOW_PORTS: optional, restricts X-Target forwarding to the listed ports (comma-separated); unset = all
	// loopback ports allowed. An invalid value is a config error and exits rather than falling back to all ports.
	allowPorts, err := wsclient.ParseAllowPorts(os.Getenv("ALLOW_PORTS"))
	if err != nil {
		log.Fatalf("%v", err)
	}
	sink := logsink.New()
	// Log spool: writes to AGENT_STATE_DIR/logspool only after an Enterprise platform first pulls /logblocks.
	// If the spool cannot open, only the spool is disabled; nothing else is affected.
	stateDir := getenv("AGENT_STATE_DIR", "state")
	spoolMax := int64(logspool.DefaultMax)
	if v := os.Getenv("LOG_SPOOL_MAX"); v != "" {
		n, err := logspool.ParseSize(v)
		if err != nil {
			log.Fatalf("%v", err)
		}
		spoolMax = n
	}
	spool, err := logspool.Open(filepath.Join(stateDir, "logspool"), spoolMax)
	if err != nil {
		log.Printf("logspool: cannot open, log spool disabled: %v", err)
	} else {
		sink.Spool = spool
		go spool.Run()
	}
	go func() {
		if err := sink.Listen(ctx, sinkAddr); err != nil {
			log.Printf("logsink: cannot open %s, logs disabled: %v", sinkAddr, err)
		}
	}()

	// The agent does not listen externally (the only listener is the local log intake above): without a cert
	// there is nothing to do, and exiting is clearer than idling.
	cs, err := certstore.Load(stateDir)
	if err != nil {
		log.Fatalf("certstore: %v", err)
	}
	if cs == nil {
		log.Fatalf("not joined: no certificate in %s. Run `besu-agent join --platform <host:port> --token <token>` first", stateDir)
	}

	routes := http.NewServeMux()
	routes.Handle("/host-metrics", host)
	routes.Handle("/logs", sink)
	if spool != nil {
		routes.Handle("/logblocks", spool)
	}
	wsc := wsclient.New(getenv("PLATFORM_ADDR", "localhost:8443"), cs, routes)
	wsc.AllowPorts = allowPorts
	routes.Handle("/agent-status", agentstatus.Handler(wsc.AllowPorts))
	log.Printf("node agent started (no external listener, log sink %s; node=%s)", sinkAddr, cs.NodeID())
	wsc.Run(ctx) // This is the only outbound connection; when it returns, it is time to shut down
	log.Printf("node agent stopped")
}
