import { errMsg, itemMsg } from '@/lib/errors';

/** System-generated temporary password: shown only this once. mailError = why sending failed when it was supposed to be emailed (shown here instead). */
export function ShownPasswordModal({ username, password, mailError, onClose }: { username: string; password: string; mailError?: string | null; onClose: () => void }) {
  const { t } = useTranslation();
  return (
    <Modal onClose={onClose} dismissOnOutside={false} contentClass={MODAL_SHELL}>
      <ModalHead onClose={onClose}>{t('users.shownTitle', { user: username })}</ModalHead>
      <div className="flex flex-col gap-3 px-5 py-4">
        {mailError && <p className="text-xs" style={{ color: 'var(--bsos-status-syncing-fg)' }}>{t('users.mailFailed', { reason: mailError })}</p>}
        <div className="flex items-center gap-2 rounded-md bg-elevated px-3 py-2 font-mono text-sm text-ink">
          <span className="break-all">{password}</span>
          <CopyButton value={password} variant="cell" />
        </div>
        <p className="text-xs text-ink-3">{t('users.shownHint')}</p>
      </div>
      <ModalFoot><Button variant="primary" onClick={onClose}>{t('users.shownDone')}</Button></ModalFoot>
    </Modal>
  );
}

/** Result of create / reset: the temporary password was emailed, or it is one the admin must hand over personally (with mailError when sending failed). */
export type UserCreated = { username: string; email: string | null; delivery: 'email' | 'shown'; password?: string | null; mailError?: string | null };

// Role option order: business roles first (operator, viewer), system admin last; extra Enterprise roles follow
const ROLE_ORDER: Role[] = ['operator', 'viewer', 'admin'];
const roleOptions = (): Role[] => [...ROLE_ORDER.filter((r) => ALL_ROLES.includes(r)), ...ALL_ROLES.filter((r) => !ROLE_ORDER.includes(r))];
const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

/** Commercial-edition roles (maker/checker) shown in the open-source edition's role menu: visible but not selectable, tagged "Enterprise" on the right */
const LOCKED_ROLES = ['maker', 'checker'] as const;
type LockedRole = (typeof LOCKED_ROLES)[number];

/** Role: chosen with a dropdown like elsewhere; what the selected role can do is written on the line below, so admins can choose without knowing the role definitions. */
function RolePicker({ value, onChange }: { value: Role; onChange: (r: Role) => void }) {
  const { t } = useTranslation();
  const roles: { value: Role | LockedRole; label: string }[] = roleOptions().map((r) => ({ value: r, label: t(`role.${r}`) }));
  const locked = isEnterprise ? [] : LOCKED_ROLES.map((r) => ({ value: r, label: t(`users.lockedRole.${r}`), disabled: true, tag: <EditionTag /> }));
  // Maker / checker are subdivisions of operator, listed right after operator
  const at = roles.findIndex((o) => o.value === 'operator') + 1;
  const options = [...roles.slice(0, at), ...locked, ...roles.slice(at)];
  return (
    <div className="flex flex-col gap-1.5">
      <span className="text-xs font-medium text-ink">{t('users.colRole')}</span>
      <Listbox width="w-44" aria-label={t('users.colRole')} value={value} onChange={(v) => { if (v !== 'maker' && v !== 'checker') onChange(v); }} options={options} />
      <span className="text-2xs text-ink-3">{roleDesc(t, value)}</span>
    </div>
  );
}

/**
 * Create user / reset password. Temporary passwords are always generated by the platform and must be changed at first login.
 * "Email the temporary password": checked by default if the deployment configured a mail server for password emails, grayed out otherwise;
 * unchecked, the password is shown once for the admin to hand over.
 * Create: account, role, Email (optional, required when sending by email). Reset: sends to the Email entered when the account was created; cannot send if none.
 */
export function UserFormModal({ mode, username: fixed, userEmail, onClose, onDone }: { mode: 'create' | 'reset'; username?: string; userEmail?: string | null; onClose: () => void; onDone: (result: UserCreated) => void }) {
  const { t } = useTranslation();
  const [username, setUsername] = useState(fixed ?? '');
  const [email, setEmail] = useState('');
  const [role, setRole] = useState<Role>(roleOptions()[0]);
  const mail = useQuery({ queryKey: ['accountMail'], queryFn: api.getAccountMailStatus });
  const configured = !!mail.data?.configured;
  const [sendPick, setSendPick] = useState<boolean | null>(null); // null = use the default (checked if configured)
  const canSend = configured && (mode === 'create' || !!userEmail);
  const send = canSend && (sendPick ?? true);
  const save = useMutation({
    mutationFn: async (): Promise<UserCreated> => {
      if (mode === 'create') {
        const r = await api.createLocalUser({ username: username.trim(), email: email.trim() || undefined, role, sendEmail: send });
        return { username: r.user.username, email: r.user.email ?? null, delivery: r.delivery, password: r.generatedPassword, mailError: itemMsg({ reason: r.mailReason, params: r.mailParams, error: r.mailError }) };
      }
      const r = await api.resetLocalUserPassword(fixed!, send);
      return { username: fixed!, email: r.email ?? null, delivery: r.delivery, password: r.generatedPassword, mailError: itemMsg({ reason: r.mailReason, params: r.mailParams, error: r.mailError }) };
    },
    onSuccess: onDone,
  });
  const emailOk = email.trim() === '' ? !send : EMAIL_RE.test(email.trim());
  const ready = (mode === 'create' ? !!username.trim() && emailOk : true) && !mail.isLoading;
  const sendHint = !configured ? t('users.sendNoServer') : mode === 'reset' && !userEmail ? t('users.sendNoEmail') : null;
  const sendBox = (
    <div className="flex flex-col gap-1">
      <label className={`flex items-center gap-2 text-xs ${canSend ? 'text-ink' : 'text-ink-3'}`}>
        <input type="checkbox" checked={send} disabled={!canSend} onChange={(e) => setSendPick(e.target.checked)} className="accent-accent" />
        {mode === 'reset' && userEmail ? t('users.sendTo', { email: userEmail }) : t('users.send')}
      </label>
      {sendHint && <span className="pl-6 text-2xs text-ink-3">{sendHint}</span>}
    </div>
  );

  return (
    // Same as site-wide form modals: header (✕) / content / button row; field labels text-xs font-medium text-ink
    <Modal onClose={onClose} dismissOnOutside={false} contentClass={MODAL_SHELL} autoFocusChild={mode === 'create'}>
      <ModalHead onClose={onClose}>{mode === 'create' ? t('users.addTitle') : t('users.resetTitle', { user: fixed })}</ModalHead>
      <form className="flex flex-col" onSubmit={(e) => { e.preventDefault(); if (ready) save.mutate(); }}>
        <div className="flex flex-col gap-4 px-5 py-4">
          {mode === 'create' ? (
            <>
              <label className="flex flex-col gap-1.5">
                <span className="text-xs font-medium text-ink">{t('users.colUser')}</span>
                <input value={username} onChange={(e) => setUsername(e.target.value)} autoFocus autoComplete="off" spellCheck={false} className={`${inputCls} w-full font-mono`} />
              </label>
              <RolePicker value={role} onChange={setRole} />
              {/* Email comes after role, immediately followed by the note that the temporary password is sent there */}
              <label className="flex flex-col gap-1.5">
                <span className="text-xs font-medium text-ink">{t('users.colEmail')}<span className="font-normal text-ink-3">{send ? '' : t('users.optional')}</span></span>
                <input type="email" value={email} onChange={(e) => setEmail(e.target.value)} autoComplete="off" spellCheck={false} className={`${inputCls} w-full`} />
              </label>
              {sendBox}
              <p className="text-xs text-ink-3">{send ? t('users.inviteNoteMail') : t('users.inviteNoteShown')}</p>
            </>
          ) : (
            <>
              <p className="text-xs leading-relaxed text-ink-2">{send ? t('users.resetBodyMail') : t('users.resetBodyShown')}</p>
              {sendBox}
            </>
          )}
          {save.isError && <p role="alert" className="text-xs" style={{ color: 'var(--bsos-status-error-fg)' }}>{errMsg(save.error) || t('error.title')}</p>}
        </div>
        <ModalFoot>
          <Button onClick={onClose}>{t('common.cancel')}</Button>
          <Button type="submit" variant="primary" disabled={!ready || save.isPending}>{mode === 'create' ? t('users.create') : t('users.reset')}</Button>
        </ModalFoot>
      </form>
    </Modal>
  );
}
