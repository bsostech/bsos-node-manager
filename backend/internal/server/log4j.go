package server

import (
	"fmt"
	"net"
	"net/http"
	"strconv"
)

// defaultLogSink is the agent's default log intake (matches agent/internal/logsink.DefaultAddr).
const defaultLogSink = "127.0.0.1:5170"

// besuLogPattern uses the same format as Besu's built-in config, so the log view matches what
// journald / docker logs show.
const besuLogPattern = "%d{yyyy-MM-dd HH:mm:ss.SSSZZZ} | %t | %-5level | %c{1} | %msg %throwable%n"

// BesuLog4jHandler: GET /api/v1/platform/besu-log4j2.xml?sink=<IP:port> (public; no secrets).
// Produces a log4j2 config for Besu: it still prints to stdout and additionally sends over a Socket
// to the log intake of the agent on the same host. sink is supplied by the onboarding page based on
// how Besu runs (containers on a bridge network send to docker0's IP); only IP:port is accepted,
// anything else is 400.
func BesuLog4jHandler() http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		sink := r.URL.Query().Get("sink")
		if sink == "" {
			sink = defaultLogSink
		}
		host, port, ok := parseSink(sink)
		if !ok {
			http.Error(w, "sink must be IP:port, for example 127.0.0.1:5170", http.StatusBadRequest)
			return
		}
		w.Header().Set("Content-Type", "application/xml; charset=utf-8")
		w.Header().Set("Content-Disposition", `attachment; filename="log4j2.xml"`)
		_, _ = fmt.Fprint(w, besuLog4jXML(host, port))
	}
}

// parseSink accepts only a literal IP plus a port in 1-65535; the IP is embedded directly in an XML
// attribute, so arbitrary strings must not get in.
func parseSink(s string) (host string, port int, ok bool) {
	h, p, err := net.SplitHostPort(s)
	if err != nil || net.ParseIP(h) == nil {
		return "", 0, false
	}
	n, err := strconv.Atoi(p)
	if err != nil || n < 1 || n > 65535 {
		return "", 0, false
	}
	return h, n, true
}

// besuLog4jXML: the Socket output is wrapped in Async (blocking=false): when the agent is not
// receiving, whatever cannot be sent is dropped, so Besu's logging calls never block.
// reconnectionDelayMillis makes Besu reconnect on its own when the agent starts late or restarts.
func besuLog4jXML(host string, port int) string {
	return fmt.Sprintf(`<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by the node manager platform: Besu still prints to stdout and also sends its logs to the agent on the same host (%[1]s:%[2]d); the platform reads recent logs through the agent.
     Usage: set LOG4J_CONFIGURATION_FILE=<path to this file> when starting Besu. -->
<Configuration status="WARN">
  <Appenders>
    <Console name="Console" target="SYSTEM_OUT">
      <PatternLayout pattern="%[3]s"/>
    </Console>
    <Socket name="Agent" host="%[1]s" port="%[2]d" protocol="TCP"
            reconnectionDelayMillis="5000" immediateFail="false" ignoreExceptions="true">
      <PatternLayout pattern="%[3]s"/>
    </Socket>
    <Async name="AgentAsync" blocking="false" bufferSize="4096">
      <AppenderRef ref="Agent"/>
    </Async>
  </Appenders>
  <Loggers>
    <Root level="INFO">
      <AppenderRef ref="Console"/>
      <AppenderRef ref="AgentAsync"/>
    </Root>
  </Loggers>
</Configuration>
`, host, port, besuLogPattern)
}
